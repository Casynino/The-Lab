"""ZELab's brand pictures — every one of them cut from the OFFICIAL logo.

Nino, 10 Nov 2026: "these are the official logos — use them wherever a logo is
needed". The logo is his own vector file, `brand-src/zelab-official-logo.pdf`:
a red "ZE" with a swoosh and three little blocks, and the black word "Lab".
`official_logo.py` (needs pymupdf) splits it into its parts and writes
`brand-src/official/*`; THIS script (Pillow only) turns those into everything
the site ships:

    python3 docs/mockups/official_logo.py     # only when the PDF changes
    python3 docs/mockups/brand.py

Writes into client/public/brand/:
    zelab-dark.svg / .png     the whole logo for the near-black app (black parts white)
    zelab-light.svg / .png    the whole logo in his own colours, for white pages
    lab-dark / lab-light      just the letters "Lab" (the sidebar header)
    mark-dark.svg, mark-light.svg   the red "ZE" with its swoosh and blocks
    zel-mark.png              that mark for light surfaces (the 3D sign-in scene's decals)
    app-180/192/512, maskable, favicon.png, favicon-32.png, ../favicon.ico,
    ../favicon.svg, ../apple-touch-icon.png (asked for by name at the root)
    splash/*, og-image.jpg    the home-screen set, the tab icon, the launch screens
                              and the card a shared link shows

Nothing is redrawn and no colour is retuned: his red, his black — and, as every
logo does on a dark page, the black parts white. (Before this the logo was a
drawn stand-in: a red "ZE", a big white "L" and a small "ab" built here from the
old hǎo Labs artwork. It is gone; `git log` has it.)
"""

from PIL import Image, ImageDraw, ImageFont
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
OFFICIAL = os.path.join(HERE, "brand-src", "official")
PUB = os.path.normpath(os.path.join(HERE, "..", "..", "client", "public"))
BRAND = os.path.join(PUB, "brand")
SPLASH_DIR = os.path.join(BRAND, "splash")
os.makedirs(SPLASH_DIR, exist_ok=True)

INK = (10, 10, 11)              # the app's near-black
SS = 4
F = "/System/Library/Fonts/Supplemental/"


def official(name):
    path = os.path.join(OFFICIAL, name)
    if not os.path.exists(path):
        raise SystemExit(f"missing {path} — run docs/mockups/official_logo.py first")
    return Image.open(path).convert("RGBA")


LOGO = {t: official(f"logo-{t}.png") for t in ("dark", "light")}
LAB = {t: official(f"lab-{t}.png") for t in ("dark", "light")}
MARK = {t: official(f"mark-{t}.png") for t in ("dark", "light")}
mark = MARK["dark"]             # the mark on the icons' dark tile


def fit_width(im, w):
    return im.resize((w, max(1, round(im.height * w / im.width))), Image.LANCZOS)


def lockup(tone="dark", height=320):
    """The whole official logo, `height` tall."""
    im = LOGO[tone]
    return im.resize((max(1, round(im.width * height / im.height)), height), Image.LANCZOS)


def save(im, *path):
    p = os.path.join(BRAND, *path)
    im.save(p, "PNG", optimize=True)
    print(p, im.size, os.path.getsize(p))


# ── the logo files themselves (vector for the web, PNG for everything that cannot take a vector) ──

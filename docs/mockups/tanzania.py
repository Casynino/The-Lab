"""Tanzania, simplified, projected into an SVG box.

The sign-in scene is the business: product leaving the Lab in Dar es Salaam
and going out to the regions (Nino, 9 Nov 2026 — "show a map of Tanzania,
moving boxes… this is a distribution channel"). This writes the geometry the
scene draws, so the shape is real coordinates rather than a doodle:

    python3 docs/mockups/tanzania.py > client/src/pages/tanzania.js

The border is a hand-simplified outline in degrees, projected flat with a
cos(latitude) correction so the country keeps its proportions instead of
stretching — at 6 degrees south that is a 0.6% error, which no one can see,
and it avoids carrying a projection library for one picture.
"""
import math, json

BORDER = [
 (39.25,-4.68),(39.50,-5.90),(39.00,-6.85),(39.45,-7.70),(39.80,-8.40),(39.30,-9.60),
 (40.45,-10.45),(39.20,-11.15),(38.50,-11.25),(37.50,-11.50),(36.50,-11.70),(35.60,-11.42),
 (34.90,-11.37),(34.55,-11.10),(34.28,-10.30),(33.95,-9.50),(33.60,-9.60),(32.90,-9.40),
 (32.45,-9.15),(31.95,-8.90),(31.55,-8.80),(31.00,-8.60),(30.70,-8.10),(30.35,-7.20),
 (29.80,-6.40),(29.55,-5.70),(29.40,-4.90),(29.75,-4.45),(30.40,-4.00),(30.55,-3.40),
 (30.80,-2.98),(30.45,-2.40),(30.80,-1.70),(31.80,-1.02),(32.80,-1.00),(33.90,-1.00),
 (34.00,-1.05),(34.55,-1.12),(35.30,-1.60),(36.00,-2.10),(36.90,-2.60),(37.60,-3.05),
 (37.80,-3.67),(38.40,-3.95),
]

# The Tanzanian part of Lake Victoria: the border runs through open water, so
# the lake has to be cut out of the land or the north reads as solid country.
VICTORIA = [(31.72,-1.02),(32.30,-1.00),(33.10,-1.00),(33.72,-1.02),(33.90,-1.45),
            (33.70,-2.00),(33.30,-2.42),(32.75,-2.62),(32.20,-2.48),(31.85,-2.05),
            (31.70,-1.55)]

CITIES = {
  "dar":      (39.28, -6.82),
  "arusha":   (36.68, -3.37),
  "mwanza":   (32.90, -2.52),
  "dodoma":   (35.74, -6.17),
  "mbeya":    (33.46, -8.90),
  "tanga":    (39.10, -5.07),
  "morogoro": (37.66, -6.82),
  "mtwara":   (40.18, -10.27),
  "kigoma":   (29.63, -4.88),
}

W = 1000.0
lons = [p[0] for p in BORDER]; lats = [p[1] for p in BORDER]
lon0, lon1 = min(lons), max(lons)
lat0, lat1 = min(lats), max(lats)
k = math.cos(math.radians((lat0 + lat1) / 2))     # keep the country's proportions
H = W * ((lat1 - lat0) / ((lon1 - lon0) * k))

def xy(lon, lat):
    x = (lon - lon0) / (lon1 - lon0) * W
    y = (lat1 - lat) / (lat1 - lat0) * H
    return round(x, 1), round(y, 1)

def path(points, close=True, smooth=0.0):
    """Straight between the points by default.

    An earlier version ran a quadratic through every vertex to "soften" the
    coastline and turned the country into a blob: at this scale the corners
    ARE the shape — Mtwara, the Kilimanjaro notch, the Lake Tanganyika edge.
    `smooth` blends a little rounding back in if it is ever wanted; 0 keeps
    the real outline."""
    pts = [xy(*p) for p in points]
    if not smooth:
        d = f"M{pts[0][0]} {pts[0][1]}"
        for x, y in pts[1:]:
            d += f" L{x} {y}"
        return d + (" Z" if close else "")
    d = f"M{pts[0][0]} {pts[0][1]}"
    for i in range(1, len(pts)):
        a, b = pts[i - 1], pts[i]
        cx = a[0] + (b[0] - a[0]) * smooth
        cy = a[1] + (b[1] - a[1]) * smooth
        d += f" Q{round(cx,1)} {round(cy,1)} {b[0]} {b[1]}"
    return d + (" Z" if close else "")

def route(a, b, bow=0.18):
    """A lane from the Lab to a region, bowed so it reads as a journey."""
    (x1, y1), (x2, y2) = xy(*CITIES[a]), xy(*CITIES[b])
    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
    dx, dy = x2 - x1, y2 - y1
    cx, cy = mx - dy * bow, my + dx * bow
    return f"M{round(x1,1)} {round(y1,1)} Q{round(cx,1)} {round(cy,1)} {round(x2,1)} {round(y2,1)}"

out = {
  "w": round(W), "h": round(H),
  "border": path(BORDER),
  "victoria": path(VICTORIA),
  "cities": {k2: xy(*v) for k2, v in CITIES.items()},
  "routes": {n: route("dar", n) for n in ["arusha","mwanza","dodoma","mbeya","tanga","morogoro","mtwara","kigoma"]},
}
print("/* Generated by docs/mockups/tanzania.py — do not edit by hand. */")
print("export default " + json.dumps(out, indent=2) + ";")
